import io
from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT


def set_doc_margins(doc):
    for section in doc.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1)
        section.right_margin = Inches(1)


def create_cover_letter_docx(cover_letter_text, candidate_name="Candidate"):
    """
    Creates a styled Word (.docx) document for the cover letter and returns a BytesIO buffer.
    """
    doc = Document()
    set_doc_margins(doc)

    for line in cover_letter_text.split("\n"):
        line_clean = line.strip()
        if not line_clean:
            doc.add_paragraph()
            continue

        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.line_spacing = 1.15
        run = p.add_run(line_clean)
        run.font.name = 'Calibri'
        run.font.size = Pt(11)
        run.font.color.rgb = RGBColor(33, 37, 41)

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer


def create_ats_report_markdown(analysis, candidate_name="Candidate"):
    """
    Formats the ATS audit results into a clean, downloadable Markdown report.
    """
    overall = analysis.get("score_overall", 0)
    skills_score = analysis.get("score_skills", 0)
    exp_score = analysis.get("score_experience", 0)
    format_score = analysis.get("score_formatting", 0)
    impact_score = analysis.get("score_impact", 0)
    edu_score = analysis.get("score_education", 0)

    report = f"""# 📄 ATS Resume Audit & Benchmarking Report
**Candidate**: {candidate_name}
**Overall ATS Compatibility**: {overall}%

---

## 📈 Score Breakdown
- **Overall Match**: {overall}/100
- **Skills Alignment**: {skills_score}/100
- **Experience Relevance**: {exp_score}/100
- **Quantified Impact (XYZ)**: {impact_score}/100
- **ATS Parsing & Formatting**: {format_score}/100
- **Education & Credentials**: {edu_score}/100

---

## 💡 Executive Summary
{analysis.get("executive_summary", "Detailed ATS audit analysis.")}

---

## ✨ Key Strengths
"""
    for s in analysis.get("strengths", []):
        report += f"- {s}\n"

    kw = analysis.get("keyword_analysis", {})
    matched = kw.get("matched_keywords", [])
    must_have = kw.get("missing_must_have", [])
    nice_to_have = kw.get("missing_nice_to_have", [])

    report += "\n## 🔍 Keyword Gap Analysis\n"
    report += f"**Matched Keywords ({len(matched)})**: {', '.join(matched) if matched else 'None detected'}\n\n"
    report += f"**Critical Missing Keywords ({len(must_have)})**:\n"
    for m in must_have:
        report += f"- ❌ {m}\n"

    report += f"\n**Secondary Missing Keywords ({len(nice_to_have)})**:\n"
    for n in nice_to_have:
        report += f"- ⚠️ {n}\n"

    report += "\n## 📋 Section-by-Section Health Audit\n"
    for sec in analysis.get("section_audit", []):
        status_icon = "✅" if sec.get("status") == "Pass" else "⚠️" if sec.get("status") == "Warning" else "❌"
        report += f"- {status_icon} **{sec.get('section')}** ({sec.get('status')}): {sec.get('finding')}\n"

    report += "\n## 🚀 Actionable Optimization Roadmap\n"
    for tip in analysis.get("optimization_tips", []):
        report += f"1. {tip}\n"

    report += "\n---\n*Generated by CareerAI Pro powered by Google Gemini.*"
    return report


def create_ats_report_docx(analysis, candidate_name="Candidate"):
    """
    Creates a styled Word (.docx) document of the ATS audit report.
    """
    doc = Document()
    set_doc_margins(doc)

    # Title
    p_title = doc.add_paragraph()
    run_title = p_title.add_run(f"ATS Resume Audit: {candidate_name}")
    run_title.font.name = 'Calibri'
    run_title.font.size = Pt(20)
    run_title.font.bold = True
    run_title.font.color.rgb = RGBColor(79, 70, 229)

    # Subtitle
    overall = analysis.get("score_overall", 0)
    p_sub = doc.add_paragraph()
    run_sub = p_sub.add_run(f"Overall ATS Compatibility Score: {overall}%")
    run_sub.font.name = 'Calibri'
    run_sub.font.size = Pt(13)
    run_sub.font.bold = True
    run_sub.font.color.rgb = RGBColor(37, 99, 235)

    # Scores Table
    doc.add_heading("Score Breakdown", level=2)
    table = doc.add_table(rows=6, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'

    metrics = [
        ("Overall Match", f"{overall}/100"),
        ("Skills Alignment", f"{analysis.get('score_skills', 0)}/100"),
        ("Experience Depth", f"{analysis.get('score_experience', 0)}/100"),
        ("Quantified Impact (XYZ)", f"{analysis.get('score_impact', 0)}/100"),
        ("ATS Formatting & Readiness", f"{analysis.get('score_formatting', 0)}/100"),
        ("Education & Credentials", f"{analysis.get('score_education', 0)}/100")
    ]
    for idx, (label, val) in enumerate(metrics):
        row = table.rows[idx]
        row.cells[0].paragraphs[0].add_run(label).font.bold = True
        row.cells[1].paragraphs[0].add_run(val)

    # Executive Summary
    doc.add_heading("Executive Summary", level=2)
    p_exec = doc.add_paragraph(analysis.get("executive_summary", ""))
    p_exec.paragraph_format.line_spacing = 1.15

    # Strengths
    doc.add_heading("Key Profile Strengths", level=2)
    for s in analysis.get("strengths", []):
        doc.add_paragraph(s, style='List Bullet')

    # Keyword Gaps
    doc.add_heading("Keyword Gap Analysis", level=2)
    kw = analysis.get("keyword_analysis", {})
    matched = kw.get("matched_keywords", [])
    must_have = kw.get("missing_must_have", [])

    p_m = doc.add_paragraph()
    p_m.add_run("Matched Keywords: ").font.bold = True
    p_m.add_run(", ".join(matched) if matched else "None")

    p_must = doc.add_paragraph()
    p_must.add_run("Critical Missing Keywords: ").font.bold = True
    p_must.add_run(", ".join(must_have) if must_have else "None")

    # Optimization Tips
    doc.add_heading("Actionable Optimization Roadmap", level=2)
    for tip in analysis.get("optimization_tips", []):
        doc.add_paragraph(tip, style='List Number')

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer


def create_interview_prep_docx(questions, feedback_dict, candidate_name="Candidate"):
    """
    Creates a styled Word (.docx) document of the mock interview questions & evaluations.
    """
    doc = Document()
    set_doc_margins(doc)

    p_title = doc.add_paragraph()
    run_title = p_title.add_run(f"Mock Interview Preparation & STAR Scorecard")
    run_title.font.name = 'Calibri'
    run_title.font.size = Pt(18)
    run_title.font.bold = True
    run_title.font.color.rgb = RGBColor(79, 70, 229)

    doc.add_paragraph(f"Candidate: {candidate_name}")
    doc.add_heading("Interview Questions & STAR Evaluations", level=2)

    for i, q in enumerate(questions):
        q_id = q.get("id", i + 1)
        doc.add_heading(f"Question {i+1} [{q.get('type', 'General')}]: {q.get('question')}", level=3)
        doc.add_paragraph(f"Interviewer Intent: {q.get('interviewer_intent', 'N/A')}")

        if q_id in feedback_dict:
            fb = feedback_dict[q_id]
            if "error" not in fb:
                p_score = doc.add_paragraph()
                r_score = p_score.add_run(f"Overall Rating: {fb.get('rating', '')} ({fb.get('score_total', 0)}/100)")
                r_score.font.bold = True
                r_score.font.color.rgb = RGBColor(16, 185, 129)

                star = fb.get("star_breakdown", {})
                doc.add_paragraph(
                    f"STAR Breakdown: Situation: {star.get('situation_score', 0)}/10 | "
                    f"Task: {star.get('task_score', 0)}/10 | "
                    f"Action: {star.get('action_score', 0)}/10 | "
                    f"Result: {star.get('result_score', 0)}/10"
                )

                doc.add_paragraph("Strengths:", style='List Bullet')
                for s in fb.get("strengths", []):
                    doc.add_paragraph(s, style='List Bullet 2')

                doc.add_paragraph("Growth Areas:", style='List Bullet')
                for g in fb.get("growth_areas", []):
                    doc.add_paragraph(g, style='List Bullet 2')

                doc.add_paragraph("Exemplary Model Response:")
                p_sample = doc.add_paragraph(fb.get("sample_answer", ""))
                p_sample.paragraph_format.left_indent = Inches(0.25)
        else:
            doc.add_paragraph("(No recorded response yet)")

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer


